const assert = require('node:assert/strict');
const { mkdir } = require('node:fs/promises');
const { join } = require('node:path');
const playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const baseURL = process.env.CONTEXT_BASE_URL || 'http://127.0.0.1:3101';
const screenshotDir = process.env.CONTEXT_SCREENSHOT_DIR;

async function run() {
  const browser = await playwright[process.env.CONTEXT_BROWSER || 'chromium'].launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.setDefaultTimeout(20000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 500 && !response.headers()['x-context-test']) errors.push(`${response.status()} ${response.url()}`); });
    const capture = async name => {
      if (!screenshotDir) return;
      await mkdir(screenshotDir, { recursive: true });
      await page.screenshot({ path: join(screenshotDir, `${name}.png`), fullPage: true });
    };
    await page.goto(`${baseURL}/context`);
    await page.getByRole('heading', { name: 'Your issue workspace', exact: true }).waitFor();
    await page.locator('.sidebar-issue').first().waitFor();
    const initialCount = await page.locator('.sidebar-issue').count();
    assert.ok(initialCount >= 2);
    assert.equal(await page.getByRole('tab').count(), 0);
    assert.equal(await page.getByText('Founder overview', { exact: true }).count(), 0);
    const stylesheets = await page.locator('link[rel=stylesheet]').evaluateAll(links => links.map(link => link.href));
    const firstIssue = await page.locator('.sidebar-issue').nth(0).getAttribute('href');
    const secondIssue = await page.locator('.sidebar-issue').nth(1).getAttribute('href');
    await page.locator('.sidebar-issue').nth(0).click();
    await page.locator('.records-workflow').waitFor();
    assert.equal(await page.locator('.sidebar-issue[aria-current=page]').getAttribute('href'), firstIssue);
    await page.locator(`.sidebar-issue[href="${secondIssue}"]`).click();
    await page.locator('.records-workflow').waitFor();
    assert.equal(await page.locator('.sidebar-issue[aria-current=page]').getAttribute('href'), secondIssue);
    await page.goBack();
    await page.locator('.records-workflow').waitFor();
    assert.equal(await page.locator('.sidebar-issue[aria-current=page]').getAttribute('href'), firstIssue);
    assert.deepEqual(await page.locator('link[rel=stylesheet]').evaluateAll(links => links.map(link => link.href)), stylesheets);
    await page.getByRole('link', { name: 'Submit issue', exact: true }).click();
    const title = `Browser issue ${Date.now()}`;
    const comment = 'Reproduced in staging. <img src=x onerror=alert(1)> token=COMMENT_CANARY';
    await page.getByLabel('Issue title', { exact: true }).fill(title);
    await page.getByLabel('Environment', { exact: true }).fill('staging');
    await page.getByLabel('Issue description', { exact: true }).fill('A valid PDF upload fails with an unsupported file type error.');
    await page.getByLabel('Comment', { exact: false }).fill(comment);
    await page.getByRole('button', { name: 'Refresh', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('#refresh-issues').disabled);
    assert.equal(await page.getByLabel('Issue title', { exact: true }).inputValue(), title);
    assert.equal(await page.getByLabel('Comment', { exact: false }).inputValue(), comment);
    assert.equal(await page.locator('.sidebar-issue').count(), initialCount);
    assert.deepEqual(await page.locator('link[rel=stylesheet]').evaluateAll(links => links.map(link => link.href)), stylesheets);
    await capture('01-submit-issue');
    const intakeKeys = [];
    await page.route('**/api/issues', async route => {
      const request = route.request();
      if (request.method() !== 'POST' || request.postDataJSON().action !== 'intake') return route.continue();
      intakeKeys.push(request.headers()['idempotency-key']);
      if (intakeKeys.length !== 1) return route.continue();
      const response = await route.fetch();
      assert.equal(response.status(), 200);
      await route.fulfill({ status: 502, headers: { 'content-type': 'application/json', 'x-context-test': 'lost-response' }, body: JSON.stringify({ error: 'Simulated lost response. Retry the same request.' }) });
    });
    await page.getByRole('button', { name: 'Submit issue & open lifecycle', exact: true }).click();
    await page.locator('#request-error').waitFor({ state: 'visible' });
    assert.equal(await page.getByRole('button', { name: 'Submit issue & open lifecycle', exact: true }).isDisabled(), true);
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.waitForURL(/\/context\/issues\/ISS-/);
    assert.equal(intakeKeys.length, 2);
    assert.equal(intakeKeys[0], intakeKeys[1], 'Unknown-result retries reuse the same request key');
    const issueId = new URL(page.url()).pathname.split('/').at(-1);
    const saved = async () => {
      const response = await context.request.get(`${baseURL}/api/issues?issue=${issueId}`);
      assert.equal(response.status(), 200);
      return response.json();
    };
    const waitGate = command => page.locator(`form[data-command="${command}"]`).first().waitFor({ state: 'visible' });
    await waitGate('state');
    assert.equal((await saved()).lifecycle.step, 2);
    assert.equal(await page.getByRole('button', { name: 'Next', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'View report & comment', exact: true }).click();
    assert.match(await page.locator('#detail-body').innerText(), /Reproduced in staging/);
    assert.doesNotMatch(await page.locator('#detail-body').innerText(), /COMMENT_CANARY/);
    assert.equal(await page.locator('#detail-body img').count(), 0);
    await page.getByRole('button', { name: 'Close details', exact: true }).click();
    await page.getByLabel('Responsible owner', { exact: true }).fill('Platform · Test owner');
    await page.getByRole('combobox', { name: 'Operational severity', exact: true }).selectOption('S2');
    await page.getByLabel('Assignment basis', { exact: true }).fill('Service ownership reviewed and accepted in this test.');
    await page.getByRole('button', { name: 'Save ownership', exact: true }).click();
    await waitGate('workflow_investigation');
    await page.getByLabel('Investigation findings', { exact: true }).fill('The test reproduction rejects a valid PDF with an empty MIME label. Candidate cause, not a production finding.');
    await page.getByLabel('Proposed fix and delivery tradeoff', { exact: true }).fill('Inspect file bytes server-side. One engineer-day; defer a non-urgent task.');
    await page.getByLabel('Verification plan and recorded results', { exact: true }).fill('Test valid PDF, invalid content, and size limits. Customer repository tests have not run.');
    await page.getByRole('button', { name: 'Save investigation', exact: true }).click();
    await waitGate('approve');
    await capture('02-review-gate');
    assert.equal((await saved()).lifecycle.step, 5);
    await page.reload();
    await waitGate('approve');
    await page.getByRole('button', { name: 'Approve fix', exact: true }).click();
    assert.equal((await saved()).proposal.status, 'awaiting_approval');
    await page.getByLabel('I reviewed this exact fix plan, evidence, verification status, and delivery tradeoff.').check();
    await page.getByRole('button', { name: 'Approve fix', exact: true }).click();
    await waitGate('workflow_deploy');
    assert.equal((await saved()).issue.deployed, false);
    await page.getByLabel('Deployment verification evidence', { exact: true }).fill('Simulated staging release verified: the original PDF uploads successfully.');
    await page.getByLabel('I reviewed this simulated deployment verification. No actual deployment is being performed.').check();
    await page.getByRole('button', { name: 'Record simulated deployment', exact: true }).click();
    await waitGate('map_account');
    assert.equal((await saved()).lifecycle.step, 7);
    await page.getByRole('combobox', { name: 'Verified account from the local fixture register', exact: true }).selectOption('northstar');
    await page.getByLabel('Identity verification basis', { exact: true }).fill('Known authorized support contact in the local test register.');
    await page.getByRole('button', { name: 'Record verified identity', exact: true }).click();
    await waitGate('workflow_confirm');
    assert.notEqual((await saved()).issue.state, 'resolved');
    await page.getByLabel('Customer reply / evidence', { exact: true }).fill('Explicit test customer reply: the original PDF now uploads successfully.');
    await page.getByLabel('I reviewed this separate customer response for the selected account.').check();
    await page.getByRole('button', { name: 'Record customer reply', exact: true }).click();
    await page.locator('#phase-status').filter({ hasText: 'Recovery confirmed' }).waitFor();
    assert.equal((await saved()).issue.state, 'resolved');
    await capture('03-recovery-confirmed');
    await page.reload();
    await page.locator('#phase-status').filter({ hasText: 'Recovery confirmed' }).waitFor();
    assert.equal(await page.locator('.sidebar-issue').count(), initialCount + 1);
    await page.getByLabel('Search issues', { exact: true }).fill(title);
    assert.equal(await page.locator('.sidebar-issue').count(), 1);
    assert.match(await page.locator('.sidebar-issue').innerText(), /resolved/);
    assert.equal(await page.locator('.sidebar-issue').getAttribute('aria-current'), 'page');
    await capture('04-sidebar-selection');
    for (const width of [1440, 1180, 768, 390]) {
      await page.setViewportSize({ width, height: 900 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No horizontal overflow at ${width}px`);
    }
    assert.equal(await page.getByRole('button', { name: 'Sign out', exact: true }).count(), 0);
    assert.equal((await context.request.get(`${baseURL}/api/issues?issue=${issueId}`)).status(), 200);
    for (const path of ['/demo', '/inbox', '/issues']) {
      const response = await context.request.get(`${baseURL}${path}`, { maxRedirects: 0 });
      assert.equal(response.status(), 307);
      assert.equal(response.headers().location, '/context/issues');
    }
    const legacyIssue = await context.request.get(`${baseURL}/issues?issue=${issueId}`, { maxRedirects: 0 });
    assert.equal(legacyIssue.headers().location, `/context/issues/${issueId}`);
    for (const file of ['index.html', 'app.js', 'demo-engine.js']) assert.equal((await context.request.get(`${baseURL}/context-demo/${file}`)).status(), 404);
    await page.goto(`${baseURL}/context?demo=1`);
    await page.getByRole('heading', { name: 'Your issue workspace', exact: true }).waitFor();
    assert.equal(await page.getByRole('tab').count(), 0);
    await page.route('**/api/issues', route => route.fulfill({ json: { issues: [] } }));
    await page.reload();
    await page.getByText('No issues yet. Submit your first issue to start its lifecycle.', { exact: true }).waitFor();
    await page.getByRole('link', { name: 'Submit issue', exact: true }).waitFor();
    assert.deepEqual(errors, []);
    console.log('Context workspace passed: persistent sidebar, selection/back navigation, consistent styles, retired demo routes, password-free access, saved comment, automatic lifecycle, human gates, persistence, empty state, and safe rendering.');
  } finally { await browser.close(); }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
